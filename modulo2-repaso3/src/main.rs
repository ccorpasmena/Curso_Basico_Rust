/* Ejercicio 3: Intercambio de valores

Declara dos variables: x = 5 e y = 10.

Intercambia sus valores sin usar una tercera variable temporal (pista: piensa en operaciones aritméticas). 

Al final, x debe valer 10 e y debe valer 5. */

fn main() {
    let x = 5;
    let y = 10;

    let x = x * 2;
    println!("La x vale: {x}");
    let y = y / 2;
    println!("La y vale: {y}");
    
}
